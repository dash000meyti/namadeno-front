export function seed_site(db: MockDB) {
  for (const post of db.blog) {
    const body = BODIES[post.slug];
    if (body) post.body = body;
  }
  for (const post of NEW_POSTS) if (!db.blog.some((p) => p.slug === post.slug)) db.blog.push(post);
  db.blog.sort((a, b) => b.publishedAt.localeCompare(a.publishedAt));
  for (const f of MORE_FAQ) if (!db.faq.some((x) => x.id === f.id)) db.faq.push(f);
}
